using Oracle.ManagedDataAccess.Client;
using SharpDb.Provider.Contract;

namespace SharpDb.Provider.Oracle.Tests;

/// <summary>
/// The fixture's read chokepoint, exercised against the race it exists to absorb.
/// </summary>
/// <remarks>
/// <see cref="OracleContractDatabase.ReadThroughProviderAsync{T}"/> is test infrastructure, so what
/// it is for has to be asserted somewhere or it is asserted nowhere. The tests that read a table
/// they have just created reach it incidentally, and the fixture's warm-up does too, and both would
/// go on passing if the chokepoint silently stopped retrying — a retried read that eventually
/// succeeds looks exactly like a read that never had to retry. This test creates the race
/// deliberately instead.
/// <para>
/// The read it makes is a <em>data</em> read of the new table, and that is measured rather than
/// arbitrary. <c>ORA-01466</c> is raised by the consistent read of the table's own segment, so it is
/// a data read that meets it: creating a table and then immediately running <c>SELECT count(*)</c>
/// over a read-only connection was refused 20 times out of 20 on this container, while describing
/// the same table immediately — a read of the <c>ALL_*</c> dictionary views, which is what the
/// Oracle-specific tests do — was refused 0 times out of 20. Describing it here would therefore make
/// this test green whether or not the chokepoint retried, which is the one thing it must not be.
/// </para>
/// <para>
/// The read is a real one through the Provider, so this also pins the pairing the fixture depends
/// on — the chokepoint opens a connection through the Provider and hands that connection to the
/// read, rather than reaching for one of its own.
/// </para>
/// </remarks>
/// <param name="database">The container the collection shares.</param>
[Collection(OracleContractCollection.Name)]
public sealed class OracleReadThroughProviderTests(OracleContractDatabase database)
{
    /// <summary>
    /// A table read through the chokepoint immediately after it is created is answered, not refused
    /// with <c>ORA-01466</c>.
    /// </summary>
    /// <remarks>
    /// The table lives in the spare schema, because it is seeded by this test rather than by the
    /// fixture: the shared schema must stay as the fixture's seed left it, since the shared suites
    /// assert the exact set of objects in it.
    /// </remarks>
    [SkippableFact]
    public async Task A_table_read_with_no_interval_after_it_is_created_is_answered()
    {
        database.SkipWhenUnavailable();

        await using (var seeding = new OracleConnection(database.SpareConnectionString))
        {
            await seeding.OpenAsync();

            await using var create = seeding.CreateCommand();
            create.CommandText = """
                CREATE TABLE read_through_target (
                    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
                    label VARCHAR2(20)
                )
                """;
            await create.ExecuteNonQueryAsync();
        }

        // The read the race refuses: the table's own rows, over a read-only connection, with no
        // interval after the DDL that created it.
        var rows = await database.ReadThroughProviderAsync<object?>(
            async connection =>
            {
                await using var command = connection.CreateCommand();
                command.CommandText = "SELECT count(*) FROM read_through_target";
                return await command.ExecuteScalarAsync();
            },
            database.SpareConnectionString);

        Assert.NotNull(rows);
        // The table exists and is empty, so the answer came from the table the DDL created rather
        // than from another one or from nothing at all.
        Assert.Equal(0m, Convert.ToDecimal(rows));

        // And the definition the read was about, asked once the race has been left behind.
        var schema = await database.ReadThroughProviderAsync(
            connection => database.Provider.DescribeTableAsync(
                connection,
                "read_through_target",
                CancellationToken.None),
            database.SpareConnectionString);

        Assert.NotNull(schema);
        Assert.Equal("read_through_target", schema.Name);
        Assert.True(schema.Columns.Single(column => column.Name == "id").IsAutoIncrement);
        Assert.False(schema.Columns.Single(column => column.Name == "label").IsAutoIncrement);
    }
}
