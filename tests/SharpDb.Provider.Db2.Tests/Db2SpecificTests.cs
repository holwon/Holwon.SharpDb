using IBM.Data.Db2;
using SharpDb.Core.Execution;
using SharpDb.Core.Guard;
using SharpDb.Provider.Contract;

namespace SharpDb.Provider.Db2.Tests;

/// <summary>
/// Db2-specific assertions that go beyond the shared contract: the engine's own physics, measured
/// rather than assumed.
/// </summary>
/// <param name="database">The seeded database the collection shares.</param>
[Collection(Db2ContractCollection.Name)]
public sealed class Db2SpecificTests(Db2ContractDatabase database) : IClassFixture<Db2ContractDatabase>
{
    /// <summary>
    /// Db2 folds an unquoted identifier to upper case, so the Provider reports names in lower case
    /// — which is how a caller writes them.
    /// </summary>
    [SkippableFact]
    public async Task Names_are_reported_in_lower_case()
    {
        Skip.IfNot(database.Available, database.SkipReason);

        await using var connection = await database.Provider.CreateReadOnlyConnectionAsync(
            database.ConnectionString, CancellationToken.None);

        var tables = await database.Provider.ListTablesAsync(connection, CancellationToken.None);

        // The shared schema creates 'users', 'orgs', etc. Db2 stores them as USERS, ORGS, etc.
        // The Provider folds them back to lower case.
        Assert.Contains(tables, t => t.Name == "users");
        Assert.Contains(tables, t => t.Name == "orgs");
        Assert.Contains(tables, t => t.Name == "active_users");
    }

    /// <summary>
    /// <c>FETCH FIRST n ROWS ONLY</c> is Db2's native paging syntax and the Guard accepts it.
    /// </summary>
    [Fact]
    public void FETCH_FIRST_is_accepted_by_the_Guard()
    {
        var guard = new ReadOnlyGuard(database.Provider.Policy);

        var decision = guard.Inspect("SELECT * FROM users FETCH FIRST 10 ROWS ONLY");

        Assert.True(decision.IsAllowed, decision.Reason);
    }

    /// <summary>
    /// <c>GENERATED BY DEFAULT AS IDENTITY</c> is reported as auto-increment by the Provider.
    /// </summary>
    [SkippableFact]
    public async Task Identity_columns_are_reported_as_auto_increment()
    {
        Skip.IfNot(database.Available, database.SkipReason);

        await using var connection = await database.Provider.CreateReadOnlyConnectionAsync(
            database.ConnectionString, CancellationToken.None);

        var schema = await database.Provider.DescribeTableAsync(connection, "users", CancellationToken.None);

        Assert.NotNull(schema);
        var idColumn = Assert.Single(schema.Columns, c => c.Name == "id");
        Assert.True(idColumn.IsAutoIncrement);
    }

    /// <summary>
    /// The placeholder translation respells <c>@name</c> as <c>?</c> for Db2.
    /// </summary>
    [Fact]
    public void Placeholder_translation_respells_for_Db2()
    {
        var original = "SELECT * FROM users WHERE id = @id";

        var translated = PlaceholderTranslation.ForDialect(original, database.Provider.Policy.Dialect);

        Assert.Equal("SELECT * FROM users WHERE id = ?", translated);
    }

    /// <summary>
    /// A name that does not exist is reported as not found, not as an error.
    /// </summary>
    [SkippableFact]
    public async Task A_missing_table_returns_null()
    {
        Skip.IfNot(database.Available, database.SkipReason);

        await using var connection = await database.Provider.CreateReadOnlyConnectionAsync(
            database.ConnectionString, CancellationToken.None);

        var result = await database.Provider.DescribeTableAsync(
            connection, "no_such_table", CancellationToken.None);

        Assert.Null(result);
    }

    /// <summary>
    /// <c>list_databases</c> reports the current database name.
    /// </summary>
    [SkippableFact]
    public async Task ListDatabases_reports_the_current_database()
    {
        Skip.IfNot(database.Available, database.SkipReason);

        await using var connection = await database.Provider.CreateReadOnlyConnectionAsync(
            database.ConnectionString, CancellationToken.None);

        var databases = await database.Provider.ListDatabasesAsync(connection, CancellationToken.None);

        Assert.Single(databases);
        Assert.Equal(database.DatabaseName, databases[0]);
    }

    /// <summary>
    /// The connection the Provider opens is already open.
    /// </summary>
    [SkippableFact]
    public async Task The_connection_is_open()
    {
        Skip.IfNot(database.Available, database.SkipReason);

        await using var connection = await database.Provider.CreateReadOnlyConnectionAsync(
            database.ConnectionString, CancellationToken.None);

        Assert.Equal(System.Data.ConnectionState.Open, connection.State);
    }

    /// <summary>
    /// A composite foreign key's columns are paired in key order.
    /// </summary>
    [SkippableFact]
    public async Task Composite_foreign_key_columns_are_paired_in_order()
    {
        Skip.IfNot(database.Available, database.SkipReason);

        await using var connection = await database.Provider.CreateReadOnlyConnectionAsync(
            database.ConnectionString, CancellationToken.None);

        var schema = await database.Provider.DescribeTableAsync(connection, "bookings", CancellationToken.None);

        Assert.NotNull(schema);
        var fk = Assert.Single(schema.ForeignKeys);
        Assert.Equal(2, fk.Columns.Count);
        Assert.Equal("composite_b", fk.Columns[0]);
        Assert.Equal("composite_a", fk.Columns[1]);
        Assert.Equal("b", fk.ReferencedColumns[0]);
        Assert.Equal("a", fk.ReferencedColumns[1]);
    }
}
