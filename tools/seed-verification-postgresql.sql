-- The PostgreSQL fixture `tools/verify-installed-tool.ps1` seeds before pointing the installed tool
-- at a container. It builds the same shape as the SQLite and MySQL fixtures (a table with a primary
-- key, a second with a foreign key and a covering index, a view, two rows) so every engine answers
-- the harness's identical assertions.
--
-- The account at the end is the README's own recipe, verbatim: SELECT and nothing else. The tool is
-- only ever pointed at that account, so a write the Guard somehow let through would still be refused.
--
-- The foreign key column is indexed explicitly because PostgreSQL, like SQLite, creates no index for
-- a foreign key — so without this the index list describe_table reports would differ from MySQL's
-- for a reason that is an engine implementation detail rather than a difference in the schema.

CREATE TABLE users (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(200),
    PRIMARY KEY (id)
);

CREATE TABLE orders (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    user_id INT NOT NULL,
    total NUMERIC(10,2) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_orders_user_id ON orders (user_id);

CREATE VIEW active_users AS SELECT id, name FROM users;

