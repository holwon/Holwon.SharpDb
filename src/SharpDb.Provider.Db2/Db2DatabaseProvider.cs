using System.Data.Common;
using IBM.Data.Db2;
using SharpDb.Abstractions;
using SharpDb.Abstractions.Schema;

namespace SharpDb.Provider.Db2;

/// <summary>
/// Serves IBM Db2 LUW databases, reaching them exclusively through the Driver this project owns.
/// </summary>
/// <remarks>
/// This engine's properties shape the whole Provider, and each was measured rather than assumed.
/// <para>
/// The first is that Db2 LUW has no engine-level read-only mode at all: <c>SET TRANSACTION READ
/// ONLY</c> is a syntax error, <c>SET SESSION TRANSACTION READ ONLY</c> likewise, and the
/// connection string carries no read-only intent keyword. <c>FOR READ ONLY</c> is a cursor hint
/// that does not prevent DML. The Provider therefore opens the connection as-is, with no read-only
/// modifier: the three-layer model degrades to two layers on this engine (Guard + account
/// privileges), and that is the engine's fact rather than anything SharpDb imposes (ADR 0019).
/// </para>
/// <para>
/// The second is identifier case. Db2 folds an unquoted identifier to upper case, so an object
/// created as <c>readings</c> is stored as <c>READINGS</c> and is reached by a caller writing
/// <c>readings</c>. A name the catalogue holds in all upper case is therefore reported here in
/// lower case — which is how a caller writes it, and how every other engine in this project spells
/// it — while a name that is not all upper case came from a quoted identifier and is reported
/// exactly as the catalogue holds it.
/// </para>
/// <para>
/// The third is that introspection reads the <c>SYSCAT.*</c> catalogue views rather than
/// <c>information_schema</c>, so an account needs no privilege beyond the <c>SELECT</c> it already
/// has. The connection's own schema (<c>CURRENT SCHEMA</c>) is the scope.
/// </para>
/// </remarks>
public sealed class Db2DatabaseProvider : IDatabaseProvider
{
    /// <summary>
    /// Lists the tables and views the connection's own schema holds.
    /// </summary>
    /// <remarks>
    /// <c>SYSCAT.TABLES</c> carries both tables and views, distinguished by <c>TYPE</c>:
    /// <c>'T'</c> for a table, <c>'V'</c> for a view. <c>REMARKS</c> carries the comment, or null
    /// when none was set. The scope is <c>CURRENT SCHEMA</c>, which is the schema the connection
    /// was authenticated into — the one a caller reaches by writing unqualified names.
    /// </remarks>
    private const string ListTablesSql = """
        SELECT TABNAME, TYPE, REMARKS
        FROM SYSCAT.TABLES
        WHERE TABSCHEMA = CURRENT SCHEMA AND TYPE IN ('T', 'V')
        ORDER BY TABNAME
        """;

    /// <summary>
    /// Reports the current database name.
    /// </summary>
    /// <remarks>
    /// Db2's nearest thing to a database listing is the database the connection is bound to. A
    /// Db2 database is the unit of connectivity — one connection serves one database — so the
    /// listing is one row: the database the caller is already on.
    /// </remarks>
    private const string ListDatabasesSql = """
        SELECT CURRENT SERVER FROM SYSIBM.SYSDUMMY1
        """;

    /// <summary>
    /// Finds the object a name refers to, and which kind it is, or nothing when there is none.
    /// </summary>
    /// <remarks>
    /// The name is matched the way the engine matches an identifier: a caller writing
    /// <c>users</c> reaches the object Db2 stored as <c>USERS</c> because an unquoted identifier
    /// is folded to upper case, and a caller writing a quoted name reaches only the object spelled
    /// exactly that way. An exact match outranks a folded one, because a caller who spelled the
    /// name the catalogue's way meant that object.
    /// </remarks>
    private const string DescribeExistsSql = """
        SELECT TABNAME, TYPE, REMARKS
        FROM SYSCAT.TABLES
        WHERE TABSCHEMA = CURRENT SCHEMA AND TABNAME IN (?, UPPER(?))
        ORDER BY CASE WHEN TABNAME = ? THEN 0 ELSE 1 END
        FETCH FIRST 1 ROWS ONLY
        """;

    /// <summary>
    /// Reads one row per column, in declaration order.
    /// </summary>
    /// <remarks>
    /// <c>SYSCAT.COLUMNS</c> holds the type in <c>TYPENAME</c> with the length in <c>LENGTH</c>
    /// and the scale in <c>SCALE</c>. <c>NULLS</c> is <c>'Y'</c> or <c>'N'</c>. <c>IDENTITY</c> is
    /// <c>'Y'</c> for a column declared <c>GENERATED ALWAYS AS IDENTITY</c> or <c>GENERATED BY
    /// DEFAULT AS IDENTITY</c>. <c>DEFAULT</c> holds the default expression text, or null when
    /// none was declared.
    /// </remarks>
    private const string DescribeColumnsSql = """
        SELECT COLNAME, COLNO, TYPENAME, LENGTH, SCALE, NULLS, DEFAULT, IDENTITY, REMARKS
        FROM SYSCAT.COLUMNS
        WHERE TABSCHEMA = CURRENT SCHEMA AND TABNAME = ?
        ORDER BY COLNO
        """;

    /// <summary>
    /// Reads the primary key's columns in key order.
    /// </summary>
    /// <remarks>
    /// <c>SYSCAT.TABCONST</c> with <c>TYPE = 'P'</c> names the primary key constraint;
    /// <c>SYSCAT.KEYCOLUSE</c> carries the columns with <c>COLSEQ</c> as the key's order rather
    /// than the table's, so a composite key declared <c>(b, a)</c> arrives as <c>b, a</c> even
    /// though the columns are declared the other way round.
    /// </remarks>
    private const string DescribePrimaryKeySql = """
        SELECT k.COLNAME
        FROM SYSCAT.TABCONST c
        JOIN SYSCAT.KEYCOLUSE k
          ON c.TABSCHEMA = k.TABSCHEMA AND c.TABNAME = k.TABNAME AND c.CONSTNAME = k.CONSTNAME
        WHERE c.TABSCHEMA = CURRENT SCHEMA AND c.TABNAME = ? AND c.TYPE = 'P'
        ORDER BY k.COLSEQ
        """;

    /// <summary>
    /// Reads one row per column of every foreign key, with its target and its delete and update
    /// rules.
    /// </summary>
    /// <remarks>
    /// <c>SYSCAT.REFERENCES</c> carries the table-level relationship; the column-level pairing
    /// comes from <c>SYSCAT.KEYCOLUSE</c>, joined twice — once for the foreign-key side and once
    /// for the referenced side — each keyed on its own constraint name and aligned by
    /// <c>COLSEQ</c>. <c>DELETERULE</c> and <c>UPDATERULE</c> are single-letter codes:
    /// <c>A</c> = NoAction, <c>C</c> = Cascade, <c>R</c> = Restrict, <c>S</c> = SetNull.
    /// </remarks>
    private const string DescribeForeignKeysSql = """
        SELECT r.CONSTNAME,
               r.REFTABNAME,
               fk.COLNAME AS local_column,
               fk.COLSEQ,
               pk.COLNAME AS referenced_column,
               r.DELETERULE,
               r.UPDATERULE
        FROM SYSCAT.REFERENCES r
        JOIN SYSCAT.KEYCOLUSE fk
          ON r.TABSCHEMA = fk.TABSCHEMA AND r.TABNAME = fk.TABNAME AND r.CONSTNAME = fk.CONSTNAME
        JOIN SYSCAT.KEYCOLUSE pk
          ON r.REFTABSCHEMA = pk.TABSCHEMA AND r.REFTABNAME = pk.TABNAME
         AND r.REFKEYNAME = pk.CONSTNAME AND fk.COLSEQ = pk.COLSEQ
        WHERE r.TABSCHEMA = CURRENT SCHEMA AND r.TABNAME = ?
        ORDER BY r.CONSTNAME, fk.COLSEQ
        """;

    /// <summary>
    /// Reads one row per indexed column of every index except the one backing the primary key.
    /// </summary>
    /// <remarks>
    /// <c>SYSCAT.INDEXES.UNIQUERULE</c> is <c>'U'</c> for a unique index, <c>'D'</c> for one that
    /// allows duplicates. The primary key's backing index is excluded by matching its name against
    /// the primary key constraint's name in <c>SYSCAT.TABCONST</c>: Db2 names the backing index
    /// after the constraint, and the catalogue is the authoritative source for the exclusion
    /// rather than a guess from the index's name pattern.
    /// </remarks>
    private const string DescribeIndexesSql = """
        SELECT i.INDNAME, i.UNIQUERULE, ic.COLNAME, ic.COLSEQ
        FROM SYSCAT.INDEXES i
        JOIN SYSCAT.INDEXCOLUSE ic
          ON i.INDSCHEMA = ic.INDSCHEMA AND i.INDNAME = ic.INDNAME
        WHERE i.TABSCHEMA = CURRENT SCHEMA AND i.TABNAME = ?
          AND i.INDNAME NOT IN (
              SELECT c.CONSTNAME
              FROM SYSCAT.TABCONST c
              WHERE c.TABSCHEMA = CURRENT SCHEMA AND c.TABNAME = ?
                AND c.TYPE = 'P'
          )
        ORDER BY i.INDNAME, ic.COLSEQ
        """;

    /// <inheritdoc/>
    public string Type => "db2";

    /// <inheritdoc/>
    /// <remarks>
    /// Db2's own dialect, and no denied function names. The dialect value is what makes Core
    /// replace every <c>@name</c> placeholder with <c>?</c>, because this Driver binds by position.
    /// </remarks>
    public ReadOnlyPolicy Policy => Db2ReadOnlyPolicy.Definition;

    /// <inheritdoc/>
    /// <remarks>
    /// Db2 LUW has no engine-level read-only mode: <c>SET TRANSACTION READ ONLY</c> is a syntax
    /// error, <c>SET SESSION TRANSACTION READ ONLY</c> likewise, and the connection string has no
    /// read-only intent keyword. The connection is opened as-is, with no read-only modifier. The
    /// only boundary between the caller and a write is the account's privileges (ADR 0019).
    /// </remarks>
    public async Task<DbConnection> CreateReadOnlyConnectionAsync(
        string connectionString,
        CancellationToken cancellationToken)
    {
        var connection = new DB2Connection(connectionString);
        try
        {
            await connection.OpenAsync(cancellationToken);
            return connection;
        }
        catch
        {
            await connection.DisposeAsync();
            throw;
        }
    }

    /// <inheritdoc/>
    public async Task<IReadOnlyList<TableInfo>> ListTablesAsync(
        DbConnection connection,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(connection);

        await using var command = CommandFor(connection);
        command.CommandText = ListTablesSql;

        var tables = new List<TableInfo>();
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            var type = reader.GetString(1) == "V"
                ? TableType.View
                : TableType.Table;

            tables.Add(new TableInfo(NormalizedName(reader.GetString(0)), type, CommentAt(reader, 2)));
        }

        // Ordered here rather than by the statement, because the order a caller reads is the order
        // of the lower-cased names, and the catalogue can only sort by the upper-case spelling it
        // stores. Sorting in SQL and again here would leave the first order unused.
        return tables.OrderBy(table => table.Name, StringComparer.Ordinal).ToArray();
    }

    /// <inheritdoc/>
    public async Task<TableSchema?> DescribeTableAsync(
        DbConnection connection,
        string tableName,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(connection);
        ArgumentNullException.ThrowIfNull(tableName);

        var target = await FindObjectAsync(connection, tableName, cancellationToken);
        if (target is not { } found)
        {
            return null;
        }

        var columns = await ReadColumnsAsync(connection, found.Stored, cancellationToken);
        var primaryKey = await ReadPrimaryKeyAsync(connection, found.Stored, cancellationToken);
        var foreignKeys = await ReadForeignKeysAsync(connection, found.Stored, cancellationToken);
        var indexes = await ReadIndexesAsync(connection, found.Stored, cancellationToken);

        return new TableSchema(found.Name, found.Type, found.Comment, columns, primaryKey, foreignKeys, indexes);
    }

    /// <inheritdoc/>
    public async Task<IReadOnlyList<string>> ListDatabasesAsync(
        DbConnection connection,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(connection);

        await using var command = CommandFor(connection);
        command.CommandText = ListDatabasesSql;

        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        if (!await reader.ReadAsync(cancellationToken))
        {
            return [];
        }

        return [NormalizedName(reader.GetString(0))];
    }

    /// <summary>
    /// The object a described name refers to, as the catalogue spells it.
    /// </summary>
    /// <param name="Stored">The name the catalogue holds, which every read below keys on.</param>
    /// <param name="Name">The name to report, normalised for the caller.</param>
    /// <param name="Type">Whether the object is a table or a view.</param>
    /// <param name="Comment">The object's comment, or <see langword="null"/> when it has none.</param>
    private sealed record DescribeObject(string Stored, string Name, TableType Type, string? Comment);

    /// <summary>
    /// Finds the table or view a caller named.
    /// </summary>
    /// <param name="connection">An open connection to the database.</param>
    /// <param name="tableName">The name the caller asked for, in whatever case.</param>
    /// <param name="cancellationToken">Cancels the lookup.</param>
    /// <returns>The object, or <see langword="null"/> when the schema holds no such table or view.</returns>
    private static async Task<DescribeObject?> FindObjectAsync(
        DbConnection connection,
        string tableName,
        CancellationToken cancellationToken)
    {
        await using var command = CommandFor(connection);
        command.CommandText = DescribeExistsSql;
        AddNameParameter(command, tableName);

        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        if (!await reader.ReadAsync(cancellationToken))
        {
            return null;
        }

        var stored = reader.GetString(0);
        var type = reader.GetString(1) == "V"
            ? TableType.View
            : TableType.Table;

        return new DescribeObject(stored, NormalizedName(stored), type, CommentAt(reader, 2));
    }

    /// <summary>
    /// Reads a table's columns, in declaration order.
    /// </summary>
    /// <param name="connection">An open connection to the database.</param>
    /// <param name="tableName">The name the catalogue holds.</param>
    /// <param name="cancellationToken">Cancels the read.</param>
    /// <returns>The columns.</returns>
    private static async Task<IReadOnlyList<ColumnInfo>> ReadColumnsAsync(
        DbConnection connection,
        string tableName,
        CancellationToken cancellationToken)
    {
        await using var command = CommandFor(connection);
        command.CommandText = DescribeColumnsSql;
        AddTableParameter(command, tableName);

        var columns = new List<ColumnInfo>();
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            columns.Add(new ColumnInfo(
                Name: NormalizedName(reader.GetString(0)),
                // SYSCAT.COLUMNS.COLNO is 0-based; the contract model is 1-based.
                Ordinal: reader.GetInt16(1) + 1,
                DataType: DeclaredType(reader),
                IsNullable: reader.GetString(5) == "Y",
                DefaultValue: DefaultAt(reader, 6),
                IsAutoIncrement: reader.GetString(7) == "Y",
                Comment: CommentAt(reader, 8)));
        }

        return columns;
    }

    /// <summary>
    /// Reads a table's primary key, in key order.
    /// </summary>
    /// <param name="connection">An open connection to the database.</param>
    /// <param name="tableName">The name the catalogue holds.</param>
    /// <param name="cancellationToken">Cancels the read.</param>
    /// <returns>The key's column names, ordered by their position in the key.</returns>
    private static async Task<IReadOnlyList<string>> ReadPrimaryKeyAsync(
        DbConnection connection,
        string tableName,
        CancellationToken cancellationToken)
    {
        await using var command = CommandFor(connection);
        command.CommandText = DescribePrimaryKeySql;
        AddTableParameter(command, tableName);

        var columns = new List<string>();
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            columns.Add(NormalizedName(reader.GetString(0)));
        }

        return columns;
    }

    /// <summary>
    /// Reads a table's foreign keys.
    /// </summary>
    /// <param name="connection">An open connection to the database.</param>
    /// <param name="tableName">The name the catalogue holds.</param>
    /// <param name="cancellationToken">Cancels the read.</param>
    /// <returns>One entry per foreign key.</returns>
    private static async Task<IReadOnlyList<ForeignKeyInfo>> ReadForeignKeysAsync(
        DbConnection connection,
        string tableName,
        CancellationToken cancellationToken)
    {
        await using var command = CommandFor(connection);
        command.CommandText = DescribeForeignKeysSql;
        AddTableParameter(command, tableName);

        var rows = new List<(string Name, string Table, string Local, string Referenced, string DeleteRule, string UpdateRule)>();
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            rows.Add((
                Name: NormalizedName(reader.GetString(0)),
                Table: NormalizedName(reader.GetString(1)),
                Local: NormalizedName(reader.GetString(2)),
                Referenced: NormalizedName(reader.GetString(4)),
                DeleteRule: reader.GetString(5),
                UpdateRule: reader.GetString(6)));
        }

        return rows
            .GroupBy(row => row.Name)
            .Select(group => new ForeignKeyInfo(
                Name: group.Key,
                Columns: group.Select(row => row.Local).ToArray(),
                ReferencedTable: group.First().Table,
                ReferencedColumns: group.Select(row => row.Referenced).ToArray(),
                OnDelete: Action("delete", group.First().DeleteRule),
                OnUpdate: Action("update", group.First().UpdateRule)))
            .ToArray();
    }

    /// <summary>
    /// Reads a table's indexes, excluding the one backing the primary key.
    /// </summary>
    /// <param name="connection">An open connection to the database.</param>
    /// <param name="tableName">The name the catalogue holds.</param>
    /// <param name="cancellationToken">Cancels the read.</param>
    /// <returns>One entry per index.</returns>
    private static async Task<IReadOnlyList<IndexInfo>> ReadIndexesAsync(
        DbConnection connection,
        string tableName,
        CancellationToken cancellationToken)
    {
        await using var command = CommandFor(connection);
        command.CommandText = DescribeIndexesSql;
        AddTableParameterTwice(command, tableName);

        var rows = new List<(string Name, bool IsUnique, string? Column)>();
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            rows.Add((
                Name: NormalizedName(reader.GetString(0)),
                IsUnique: reader.GetString(1) == "U",
                Column: reader.IsDBNull(2) ? null : NormalizedName(reader.GetString(2))));
        }

        return rows
            .GroupBy(row => row.Name)
            .Select(group => new IndexInfo(
                Name: group.Key,
                IsUnique: group.First().IsUnique,
                Columns: group.Where(row => row.Column is not null).Select(row => row.Column!).ToArray()))
            .ToArray();
    }

    /// <summary>
    /// Reports a catalogue name the way a caller writes it.
    /// </summary>
    /// <param name="stored">The name the catalogue holds.</param>
    /// <returns>The name to report.</returns>
    /// <remarks>
    /// Db2 folds an unquoted identifier to upper case, so an all-upper-case name is one a caller
    /// writes in lower case and is reported that way. A name with any lower-case letter in it came
    /// from a quoted identifier, which is not folded, and is reported exactly as the catalogue
    /// holds it — reporting it folded would name an object that does not exist.
    /// </remarks>
    private static string NormalizedName(string stored) =>
        stored.All(character => !char.IsLetter(character) || char.IsUpper(character))
            ? stored.ToLowerInvariant()
            : stored;

    /// <summary>
    /// Reassembles a column's declared type from the catalogue columns.
    /// </summary>
    /// <param name="reader">The reader positioned on a column's row.</param>
    /// <returns>The declaration, as a caller would write it.</returns>
    /// <remarks>
    /// Db2 keeps the base type in <c>TYPENAME</c>, its length in <c>LENGTH</c> and its scale in
    /// <c>SCALE</c>. Types that carry a size are reported with one; a <c>DATE</c> or
    /// <c>INTEGER</c> has no length to report. <c>DECIMAL</c> and <c>NUMERIC</c> are reported
    /// with both precision and scale when the scale is non-zero.
    /// </remarks>
    private static string DeclaredType(DbDataReader reader)
    {
        var type = reader.GetString(2);
        var length = reader.GetInt32(3);
        var scale = reader.GetInt32(4);

        return type switch
        {
            "VARCHAR" or "CHAR" or "GRAPHIC" or "VARGRAPHIC" => $"{type}({length})",
            "VARBINARY" => $"{type}({length})",
            "DECIMAL" or "NUMERIC" when scale > 0 => $"{type}({length},{scale})",
            "DECIMAL" or "NUMERIC" => $"{type}({length})",
            _ => type,
        };
    }

    /// <summary>
    /// Reads a column's default.
    /// </summary>
    /// <param name="reader">The reader positioned on a column's row.</param>
    /// <param name="ordinal">The default's position in the row.</param>
    /// <returns>The default, or <see langword="null"/> when the column has none.</returns>
    private static string? DefaultAt(DbDataReader reader, int ordinal)
    {
        if (reader.IsDBNull(ordinal))
        {
            return null;
        }

        var value = reader.GetString(ordinal).TrimEnd();

        return string.IsNullOrWhiteSpace(value) ? null : value;
    }

    /// <summary>
    /// Translates the catalogue's referential action code into the action it names.
    /// </summary>
    /// <param name="direction">Whether the rule governs deletes or updates, for the error message.</param>
    /// <param name="code">The single-letter code from <c>SYSCAT.REFERENCES</c>.</param>
    /// <returns>The action.</returns>
    /// <exception cref="ArgumentOutOfRangeException">The code is not one the server documents.</exception>
    /// <remarks>
    /// The four codes are Db2's own and are documented rather than guessed. An unrecognised one
    /// fails loudly: a foreign key whose action silently became <c>NoAction</c> would be a lie
    /// about what deleting or updating a row does.
    /// </remarks>
    private static ForeignKeyAction Action(string direction, string code) => code switch
    {
        "A" => ForeignKeyAction.NoAction,
        "C" => ForeignKeyAction.Cascade,
        "R" => ForeignKeyAction.Restrict,
        "S" => ForeignKeyAction.SetNull,
        _ => throw new ArgumentOutOfRangeException(
            nameof(code),
            code,
            $"Db2 reported a foreign key {direction} rule this Provider does not know."),
    };

    /// <summary>
    /// Reads a comment that may be absent.
    /// </summary>
    /// <param name="reader">The reader positioned on a row.</param>
    /// <param name="ordinal">The comment's position in the row.</param>
    /// <returns>The comment, or <see langword="null"/> when the object carries none.</returns>
    private static string? CommentAt(DbDataReader reader, int ordinal)
    {
        if (reader.IsDBNull(ordinal))
        {
            return null;
        }

        var comment = reader.GetString(ordinal);

        return string.IsNullOrWhiteSpace(comment) ? null : comment;
    }

    /// <summary>
    /// Binds the name a caller asked for, once for each occurrence in the statement.
    /// </summary>
    /// <param name="command">The command to bind to.</param>
    /// <param name="tableName">The name the caller asked for.</param>
    /// <remarks>
    /// The <c>DescribeExistsSql</c> statement has three <c>?</c> placeholders: two in the
    /// <c>IN</c> clause (the raw name and its upper-case form) and one in the <c>CASE</c>
    /// expression (the upper-case form, because the catalogue stores names in upper case). The
    /// Driver binds by position, so each placeholder consumes one parameter.
    /// </remarks>
    private static void AddNameParameter(DbCommand command, string tableName)
    {
        // First ?: the raw name (matches a quoted-identifier object stored as-is).
        var raw = command.CreateParameter();
        raw.Value = tableName;
        command.Parameters.Add(raw);

        // Second ?: the upper-cased name (matches an unquoted-identifier object folded to upper).
        var upper = command.CreateParameter();
        upper.Value = tableName.ToUpperInvariant();
        command.Parameters.Add(upper);

        // Third ?: the upper-cased name again, for the ORDER BY CASE expression.
        var orderUpper = command.CreateParameter();
        orderUpper.Value = tableName.ToUpperInvariant();
        command.Parameters.Add(orderUpper);
    }

    /// <summary>
    /// Binds the table name for a single-occurrence query.
    /// </summary>
    private static void AddTableParameter(DbCommand command, string tableName)
    {
        var parameter = command.CreateParameter();
        parameter.Value = tableName;
        command.Parameters.Add(parameter);
    }

    /// <summary>
    /// Binds the table name for the index query, which has two <c>?</c> placeholders.
    /// </summary>
    private static void AddTableParameterTwice(DbCommand command, string tableName)
    {
        for (var i = 0; i < 2; i++)
        {
            var parameter = command.CreateParameter();
            parameter.Value = tableName;
            command.Parameters.Add(parameter);
        }
    }

    /// <summary>
    /// Creates a command ready to carry positional parameters.
    /// </summary>
    /// <param name="connection">The connection the command belongs to.</param>
    /// <returns>The command, ready for a statement with <c>?</c> placeholders.</returns>
    /// <remarks>
    /// Measured: this Driver binds by position rather than by name, so every occurrence of a
    /// placeholder in the statement needs its own parameter — a statement with three <c>?</c>
    /// needs three parameters, each carrying the corresponding value.
    /// </remarks>
    private static DbCommand CommandFor(DbConnection connection)
    {
        var command = connection.CreateCommand();
        return command;
    }
}
